/** Second digit of the SPBU code, as the backend's demo seeder assigns it. */
const OWNERSHIP_DIGIT = { Coco: 1, Codo: 3, Dodo: 4 } as const;

type Ownership = keyof typeof OWNERSHIP_DIGIT;
type RegionalKey = keyof typeof REGIONAL;

type Input = {
  urutan: number;
  regional: RegionalKey;
  tipeKepemilikan: Ownership;
  nama: string;
  alamat: string;
  kodePos: string;
  kota: string;
  provinsi: string;
  lat: number;
  lon: number;
  produk: string[];
  fasilitas: string[];
  dispenser: number;
  nozzle: number;
  rating: number | null;
  ulasan: number;
  status?: SpbuFixture["status"];
  telepon?: string;
  operasiSejak?: string;
};

function make(input: Input): SpbuFixture {
  const regional = REGIONAL[input.regional];
  const digit = OWNERSHIP_DIGIT[input.tipeKepemilikan];

  return {
    // Stable ids keep React keys and query caches predictable across reloads.
    id: `mock-${String(input.urutan).padStart(5, "0")}`,
    kodeSpbu: `${regional.nomor}${digit}.${String(input.urutan).padStart(5, "0")}`,
    nama: input.nama,
    alamat: input.alamat,
    kodePos: input.kodePos,
    kota: input.kota,
    provinsi: input.provinsi,
    regional: regional.kode,
    regionalNama: regional.nama,
    tipeKepemilikan: input.tipeKepemilikan,
    status: input.status ?? "Aktif",
    jumlahDispenser: input.dispenser,
    jumlahNozzle: input.nozzle,
    tanggalOperasi: input.operasiSejak ?? null,
    nomorTelepon: input.telepon ?? null,
    rating: input.rating,
    jumlahUlasan: input.ulasan,
    latitude: input.lat,
    longitude: input.lon,
    produk: input.produk,
    produkNama: input.produk.map((code) => PRODUCT_NAMES[code] ?? code),
    fasilitas: input.fasilitas,
    fasilitasNama: input.fasilitas.map((code) => FACILITY_NAMES[code] ?? code),
  };
}

